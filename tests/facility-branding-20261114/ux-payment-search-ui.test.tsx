// @vitest-environment jsdom
import { act, cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, expect, it, vi } from "vitest";
const mocks = vi.hoisted(() => ({ members: vi.fn(), invoices: vi.fn() }));
vi.mock("@/lib/actions/people", () => ({ listMembersAction: mocks.members }));
vi.mock("@/lib/actions/invoices", () => ({ listMemberInvoicesAction: mocks.invoices }));
vi.mock("@/components/reception/payment-record-recovery-form", () => ({ PaymentRecordRecoveryForm: ({ invoice, onRecorded }: { invoice: { id: string }; onRecorded: () => Promise<unknown> }) => <><p data-testid="selected-invoice">{invoice.id}</p><button type="button" onClick={() => void onRecorded()}>Simulate recorded</button></> }));
import { PaymentRecordForm } from "@/components/payment-record-form";

afterEach(() => { cleanup(); vi.resetAllMocks(); });
it("submits search semantically once while pending and announces distinct results", async () => {
  let resolve!: (value: unknown[]) => void;
  mocks.members.mockReturnValue(new Promise((done) => { resolve = done; }));
  render(<PaymentRecordForm />);
  const input = screen.getByTestId("payment-member-search");
  fireEvent.change(input, { target: { value: "SITE-123" } });
  const form = input.closest("form");
  expect(form).not.toBeNull();
  if (!form) return;
  fireEvent.submit(form);
  fireEvent.submit(form);
  expect(mocks.members).toHaveBeenCalledTimes(1);
  expect(mocks.members).toHaveBeenCalledWith({ search: "SITE-123" });
  await act(async () => resolve([{ memberId: "m1", fullName: "Same Name", memberCode: "SITE-123", locationName: "North" }, { memberId: "m2", fullName: "Same Name", memberCode: "SITE-456", locationName: "South" }]));
  expect(screen.getByRole("status").textContent).toMatch(/2 members/i);
  expect(screen.getByTestId("payment-member-m1").textContent).toContain("North");
  expect(screen.getByTestId("payment-member-m2").textContent).toContain("South");
});
it("does not submit Enter during IME composition", async () => {
  render(<PaymentRecordForm />);
  const input = screen.getByTestId("payment-member-search");
  fireEvent.change(input, { target: { value: "नाम" } });
  fireEvent.compositionStart(input);
  fireEvent.keyDown(input, { key: "Enter", isComposing: true, keyCode: 229 });
  expect(mocks.members).not.toHaveBeenCalled();
  fireEvent.compositionEnd(input);
  const form = input.closest("form");
  expect(form).not.toBeNull();
  if (form) fireEvent.submit(form);
  await waitFor(() => expect(mocks.members).toHaveBeenCalledTimes(1));
});
it("does not replace the selected member's invoice when an older lookup returns late", async () => {
  let resolveFirst!: (value: unknown[]) => void;
  mocks.members.mockResolvedValue([{ memberId: "m1", fullName: "First", memberCode: "A1", locationName: "North" }, { memberId: "m2", fullName: "Second", memberCode: "A2", locationName: "North" }]);
  mocks.invoices.mockImplementation((id: string) => id === "m1" ? new Promise((done) => { resolveFirst = done; }) : Promise.resolve([{ id: "inv-2", invoiceNumber: "INV-2", status: "issued", outstandingPaise: 10000, dueOn: "2026-11-14" }]));
  render(<PaymentRecordForm />);
  const input = screen.getByTestId("payment-member-search");
  fireEvent.change(input, { target: { value: "Member" } });
  fireEvent.submit(input.closest("form")!);
  fireEvent.click(await screen.findByTestId("payment-member-m1"));
  fireEvent.submit(input.closest("form")!);
  fireEvent.click(await screen.findByTestId("payment-member-m2"));
  expect((await screen.findByTestId("selected-invoice")).textContent).toBe("inv-2");
  await act(async () => resolveFirst([{ id: "inv-1", invoiceNumber: "INV-1", status: "issued", outstandingPaise: 10000, dueOn: "2026-11-14" }]));
  expect(screen.getByTestId("selected-invoice").textContent).toBe("inv-2");
});
it("keeps the chosen invoice selected after a partial-payment refresh", async () => {
  const first = { id: "inv-1", invoiceNumber: "INV-1", status: "issued", outstandingPaise: 10000, dueOn: "2026-11-14" };
  const second = { id: "inv-2", invoiceNumber: "INV-2", status: "issued", outstandingPaise: 20000, dueOn: "2026-11-14" };
  mocks.members.mockResolvedValue([{ memberId: "m1", fullName: "Member", memberCode: "A1", locationName: "North" }]);
  mocks.invoices.mockResolvedValueOnce([first, second]).mockResolvedValueOnce([first, { ...second, outstandingPaise: 10000 }]);
  render(<PaymentRecordForm />);
  const input = screen.getByTestId("payment-member-search");
  fireEvent.change(input, { target: { value: "A1" } });
  fireEvent.submit(input.closest("form")!);
  fireEvent.click(await screen.findByTestId("payment-member-m1"));
  fireEvent.click(await screen.findByTestId("payment-invoice-inv-2"));
  expect(screen.getByTestId("selected-invoice").textContent).toBe("inv-2");
  fireEvent.click(screen.getByRole("button", { name: "Simulate recorded" }));
  await waitFor(() => expect(mocks.invoices).toHaveBeenCalledTimes(2));
  expect(screen.getByTestId("selected-invoice").textContent).toBe("inv-2");
});
it("says the payment was recorded when only the invoice refresh fails", async () => {
  mocks.members.mockResolvedValue([{ memberId: "m1", fullName: "Member", memberCode: "A1", locationName: "North" }]);
  mocks.invoices.mockResolvedValueOnce([{ id: "inv-1", invoiceNumber: "INV-1", status: "issued", outstandingPaise: 10000, dueOn: "2026-11-14" }]).mockRejectedValueOnce(new Error("offline"));
  render(<PaymentRecordForm />);
  const input = screen.getByTestId("payment-member-search");
  fireEvent.change(input, { target: { value: "A1" } });
  fireEvent.submit(input.closest("form")!);
  fireEvent.click(await screen.findByTestId("payment-member-m1"));
  await screen.findByTestId("selected-invoice");
  fireEvent.click(screen.getByRole("button", { name: "Simulate recorded" }));
  expect((await screen.findByRole("alert")).textContent).toMatch(/Payment recorded, but the invoice list could not be refreshed/);
});
it("does not allow a previous search result to be chosen during another search", async () => {
  let resolve!: (value: unknown[]) => void;
  mocks.members.mockResolvedValueOnce([{ memberId: "m1", fullName: "Member", memberCode: "A1", locationName: "North" }]).mockReturnValueOnce(new Promise((done) => { resolve = done; }));
  render(<PaymentRecordForm />);
  const input = screen.getByTestId("payment-member-search");
  fireEvent.change(input, { target: { value: "A1" } });
  fireEvent.submit(input.closest("form")!);
  const oldResult = await screen.findByTestId("payment-member-m1") as HTMLButtonElement;
  fireEvent.change(input, { target: { value: "A2" } });
  fireEvent.submit(input.closest("form")!);
  expect(oldResult.disabled).toBe(true);
  fireEvent.click(oldResult);
  expect(mocks.invoices).not.toHaveBeenCalled();
  await act(async () => resolve([]));
});
